// Optional UI smoke test: requires Playwright and Chromium.
// Run against an isolated demo server (see README). Creates a fictitious client.
const {chromium}=require('playwright');
const password=process.env.EVOOLUI_DEMO_PASSWORD;
if(!password)throw Error('Defina EVOOLUI_DEMO_PASSWORD para o banco de demonstração.');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.EVOOLUI_CHROMIUM?{executablePath:process.env.EVOOLUI_CHROMIUM}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.EVOOLUI_TEST_URL||'http://127.0.0.1:8000');
 await page.getByLabel('E-mail',{exact:true}).fill('admin@evoolui.test');
 await page.getByLabel('Senha',{exact:true}).fill(password);
 await page.getByRole('button',{name:/Entrar na plataforma/}).click();
 await page.getByRole('heading',{name:/Tudo pronto/}).waitFor();
 await page.screenshot({path:'/tmp/evoolui-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Clientes',exact:true}).click();
 await page.getByRole('button',{name:'Novo cliente',exact:true}).click();
 await page.getByLabel('Nome da empresa').fill('Cliente teste navegador • fictício');
 await page.getByLabel('Nome do responsável').fill('Responsável fictício');
 await page.getByLabel('Contrato mensal').fill('1250.50');
 await page.getByLabel('Funcionários responsáveis').selectOption('3');
 await page.getByRole('button',{name:'Salvar alterações'}).click();
 await page.getByRole('cell',{name:/Cliente teste navegador/}).first().waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Clientes',exact:true}).click();
 await page.getByRole('cell',{name:/Cliente teste navegador/}).first().waitFor();
 await page.getByRole('button',{name:'Agenda',exact:true}).click();
 await page.locator('.calendar-grid').waitFor();
 await page.getByRole('button',{name:'Novo compromisso',exact:true}).click();
 await page.getByLabel('Título',{exact:true}).fill('Gravação de teste • fictícia');
 await page.getByLabel('Cliente',{exact:true}).selectOption('1');
 await page.getByLabel('Responsável',{exact:true}).selectOption('3');
 const day=await page.evaluate(async()=>{const s=await (await fetch('/api/state')).json();let d=new Date('2035-04-05T12:00:00Z');while(s.events.some(e=>e.starts_at.startsWith(d.toISOString().slice(0,10))))d.setUTCDate(d.getUTCDate()+1);return d.toISOString().slice(0,10);});
 await page.getByLabel('Início',{exact:true}).fill(day+'T10:00');
 await page.getByLabel('Término',{exact:true}).fill(day+'T11:00');
 await page.getByRole('button',{name:'Salvar alterações'}).click();
 await page.waitForFunction(()=>!document.querySelector('dialog').open);
 await page.getByRole('button',{name:/Tarefas/}).first().click();
 await page.getByRole('button',{name:'Nova tarefa',exact:true}).click();
 await page.getByLabel('Título',{exact:true}).fill('Tarefa do navegador • fictícia');
 await page.getByLabel('Responsável',{exact:true}).selectOption('3');
 await page.getByRole('button',{name:'Salvar alterações'}).click();
 await page.getByRole('cell',{name:/Tarefa do navegador/}).first().waitFor();
 await page.getByRole('button',{name:'Visão geral',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/evoolui-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Page overflows mobile viewport');

 await page.getByRole('button',{name:'Minha conta e sair'}).click();
 await page.getByRole('button',{name:'Sair da plataforma'}).click();
 await page.getByLabel('E-mail',{exact:true}).fill('cliente@evoolui.test');
 await page.getByLabel('Senha',{exact:true}).fill(password);
 await page.getByRole('button',{name:/Entrar na plataforma/}).click();
 await page.getByRole('heading',{name:/Tudo pronto/}).waitFor();
 if(await page.getByText('Receita contratada',{exact:true}).count())throw Error('Client sees financial data');
 await page.getByRole('button',{name:'Clientes',exact:true}).click();
 if(await page.locator('tbody tr').count()!==1)throw Error('Client sees other companies');
 await page.getByRole('button',{name:/Detalhes/}).click();
 await page.locator('dialog fieldset[disabled]').waitFor();
 await page.getByRole('button',{name:'Fechar',exact:true}).last().click();
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: login, client creation + reload persistence, scheduling, tasks, calendar, mobile viewport, mobile logout and client read-only scope; no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
